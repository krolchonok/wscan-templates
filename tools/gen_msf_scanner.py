def includes(src: str) -> list[str]:
    return re.findall(r"include\s+((?:Msf|Rex)::\S+)", src)


def is_simple_tcp_udp(incs: list[str]) -> bool:
    # Msf::Auxiliary::UDPScanner is a scan-loop helper (batching/threading),
    # not a protocol mixin: modules using it send their own raw UDP probe via
    # build_probe/scanner_send (see extract_build_probe). It never includes an
    # Exploit::Remote::Udp mixin, so without this it would never reach the
    # rem-based checks below and always be silently dropped pre-analysis.
    # DRDoS (amplification/reflection) modules ride on top of UDPScanner too —
    # exclude those explicitly, same reasoning as the DoS-module skip below.
    if any("Auxiliary::UDPScanner" in i for i in incs):
        return not any("Auxiliary::DRDoS" in i for i in incs)
    rem = [i for i in incs if "Exploit::Remote" in i or i.startswith("Rex::Proto")]
    if not rem:
        return False
    # Allow only Tcp/Udp among Exploit::Remote; reject heavy / other protos.
    for i in rem:
        if HEAVY_MIXIN.search(i):
            # SIP mixin is heavy for us (create_probe in mixin); skip.
            return False
        if "Exploit::Remote" in i and not OK_REMOTE.search(i):
            return False
        if i.startswith("Rex::Proto"):
            return False
    return any(OK_REMOTE.search(i) for i in rem)


def extract_info_field(src: str, key: str) -> str:
    # 'Name' => '...'  or "Name" => %q{...} or multiline %q{ }
    pat = rf"['\"]{key}['\"]\s*=>\s*(%q\{{(.*?)\}}|%q\[(.*?)\]|'((?:\\'|[^'])*)'|\"((?:\\\"|[^\"])*)\")"
    m = re.search(pat, src, re.S)
    if not m:
        return ""
    for g in m.groups()[1:]:
        if g is not None:
            return re.sub(r"\s+", " ", g.strip())
    return ""


def extract_authors(src: str) -> str:
    m = re.search(r"['\"]Author['\"]\s*=>\s*(\[[^\]]*\]|'[^']+'|\"[^\"]+\")", src, re.S)
    if not m:
        return "metasploit"
    block = m.group(1)
    names = re.findall(r"['\"]([^'\"]+)['\"]", block)
    if not names:
        return "metasploit"
    # Strip emails in angle brackets noise for yaml friendliness
    cleaned = []
    for n in names:
        n = re.sub(r"\s*<[^>]+>", "", n).strip()
        if n:
            cleaned.append(n)
    return ",".join(cleaned) if cleaned else "metasploit"


def extract_cves(src: str) -> list[str]:
    found = set(re.findall(r"\bCVE-\d{4}-\d+\b", src, re.I))
    # MSF style: [ 'CVE', '2014-0659' ]
    for m in re.finditer(r"\[\s*['\"]CVE['\"]\s*,\s*['\"](\d{4}-\d+)['\"]\s*\]", src, re.I):
        found.add(f"CVE-{m.group(1)}")
    return sorted(found)


def extract_rport(src: str) -> int | None:
    for pat in (
        r"Opt::RPORT\(\s*(\d+)\s*\)",
        r"OptPort\.new\(\s*['\"]RPORT['\"]\s*,\s*\[[^\]]*?(\d{2,5})",
        r"Opt::RPORT\(\s*default\s*:\s*(\d+)",
    ):
        m = re.search(pat, src)
        if m:
            return int(m.group(1))
    # PORTS default like "80,8080,443,3460" — take last (often service default)
    m = re.search(
        r"OptString\.new\(\s*['\"]PORTS['\"]\s*,\s*\[.*?['\"]([\d,\s]+)['\"]\s*\]",
        src,
        re.S,
    )
    if m:
        ports = [int(p) for p in re.findall(r"\d+", m.group(1))]
        if ports:
            return ports[-1]
    return None


def decode_ruby_string(literal: str) -> bytes | None:
    """Decode a Ruby single/double-quoted string literal to bytes."""
    literal = literal.strip()
    if len(literal) < 2:
        return None
    q = literal[0]
    if q not in "'\"":
        return None
    if literal[-1] != q:
        return None
    body = literal[1:-1]
    if q == "'":
        # Ruby single quotes: only \\ and \'
        return body.replace("\\\\", "\\").replace("\\'", "'").encode("latin-1", errors="replace")

    out = bytearray()
    i = 0
    while i < len(body):
        if body[i] != "\\":
            out.append(ord(body[i]) & 0xFF)
            i += 1
            continue
        i += 1
        if i >= len(body):
            break
        c = body[i]
        if c == "x" and i + 2 < len(body):
            hx = body[i + 1 : i + 3]
            if re.fullmatch(r"[0-9A-Fa-f]{2}", hx):
                out.append(int(hx, 16))
                i += 3
                continue
        if c == "n":
            out.append(0x0A)
            i += 1
            continue
        if c == "r":
            out.append(0x0D)
            i += 1
            continue
        if c == "t":
            out.append(0x09)
            i += 1
            continue
        if c == "0" and (i + 1 >= len(body) or body[i + 1] not in "0123456789"):
            out.append(0)
            i += 1
            continue
        if c in "\\\"'":
            out.append(ord(c))
            i += 1
            continue
        # octal \NNN
        m = re.match(r"([0-7]{1,3})", body[i:])
        if m:
            out.append(int(m.group(1), 8) & 0xFF)
            i += len(m.group(1))
            continue
        out.append(ord(c) & 0xFF)
        i += 1
    return bytes(out)


def eval_bytes_expr(expr: str, src: str, depth: int = 0) -> bytes | None:
    """Best-effort constant-fold a Ruby expression that builds a byte string."""
    if depth > 8:
        return None
    expr = expr.strip().rstrip(",").strip()
    if not expr:
        return None

    # Strip outer parens
    while expr.startswith("(") and expr.endswith(")"):
        depth_p = 0
        ok = True
        for i, ch in enumerate(expr):
            if ch == "(":
                depth_p += 1
            elif ch == ")":
                depth_p -= 1
                if depth_p == 0 and i != len(expr) - 1:
                    ok = False
                    break
        if ok and depth_p == 0:
            expr = expr[1:-1].strip()
        else:
            break

    # String literal
    if (expr.startswith('"') and expr.endswith('"')) or (expr.startswith("'") and expr.endswith("'")):
        # careful with escaped quotes — use regex
        m = re.match(r"('(?:\\'|[^'])*'|\"(?:\\\"|\\x[0-9A-Fa-f]{2}|\\[nrt0]|[^\"])*\")\s*$", expr)
        if m:
            return decode_ruby_string(m.group(1))

    # "\x00" * N  or  "\x00" * 0x100
    m = re.match(
        r"('(?:\\'|[^'])*'|\"(?:\\\"|\\x[0-9A-Fa-f]{2}|\\[nrt0]|[^\"])*\")\s*\*\s*(0x[0-9A-Fa-f]+|\d+)\s*$",
        expr,
    )
    if m:
        base = decode_ruby_string(m.group(1))
        if base is None:
            return None
        n = int(m.group(2), 0)
        if n < 0 or n > 65536:
            return None
        return base * n

    # Rex::Text.rand_text(N) / rand_text_alpha(N) / rand_text_alpha_lower(N) / …
    m = re.match(
        r"Rex::Text\.rand_text(?:_alpha(?:_lower|_upper)?|_alphanumeric|_english|_numeric|_highascii)?\(\s*(?:rand\(\s*(\d+)\s*\)\s*\+\s*)?(\d+)\s*\)",
        expr,
    )
    if m:
        # Use upper bound if rand(n)+m form: rand(a)+b → a+b-1 approx as a+b
        a = int(m.group(1)) if m.group(1) else 0
        b = int(m.group(2))
        n = a + b if a else b
        n = max(1, min(n, 256))
        return b"A" * n

    # CLASS_CONST or SMI_PROBE (Ruby constant)
    if re.fullmatch(r"[A-Z][A-Z0-9_]*", expr):
        return resolve_constant(expr, src, depth + 1)

    # datastore['path'] with default — handled via default OptString
    m = re.match(r"datastore\[['\"](\w+)['\"]\]", expr)
    if m:
        key = m.group(1)
        # OptString.new('path', [true, '...', 'default'])
        dm = re.search(
            rf"OptString\.new\(\s*['\"]{re.escape(key)}['\"]\s*,\s*\[[^\]]*?['\"]([^'\"]*)['\"]\s*\]",
            src,
            re.I,
        )
        if dm:
            return dm.group(1).encode()
        if key.lower() == "path":
            return b""  # gopher root
        return None

    # method call with no args: foo / foo()
    m = re.match(r"([a-zA-Z_]\w*)\(\s*\)\s*$", expr) or re.match(r"([a-zA-Z_]\w*)\s*$", expr)
    if m and m.group(1) not in {"nil", "true", "false", "super", "connect", "disconnect"}:
        name = m.group(1)
        # def name ... "literal" ... end  — take concatenation of string literals in method
        mm = re.search(
            rf"def\s+{re.escape(name)}\b(?:\([^)]*\))?\s*\n(.*?)(?=\n\s*def\s+|\nend\s*\n)",
            src,
            re.S,
        )
        if mm:
            body = mm.group(1)
            # If method is just a string concat return
            returned = resolve_method_body_bytes(body, src, depth + 1)
            if returned is not None:
                return returned

    # [n].pack("C"|"N"|"V"|"n"|"v")
    m = re.match(r"\[\s*(0x[0-9A-Fa-f]+|\d+)\s*\]\.pack\(\s*['\"]([CNnVv])['\"]\s*\)", expr)
    if m:
        val = int(m.group(1), 0)
        fmt = m.group(2)
        endian = {"C": "B", "N": ">I", "V": "<I", "n": ">H", "v": "<H"}[fmt]
        try:
            return struct.pack(endian if fmt != "C" else "B", val & (0xFF if fmt == "C" else 0xFFFFFFFF))
        except Exception:
            return None

    # [a, b, c, ...].pack("c*"|"C*")  — numeric byte list
    m = re.match(r"\[\s*(.+?)\s*\]\.pack\(\s*['\"][cC]\*['\"]\s*\)\s*$", expr)
    if m:
        parts = split_top_level(m.group(1), ",")
        out = bytearray()
        ok = True
        for p in parts:
            p = p.strip()
            # allow bare locals that resolve to small ints via assignment `x = 0x26`
            if re.fullmatch(r"0x[0-9A-Fa-f]+|\d+", p):
                out.append(int(p, 0) & 0xFF)
                continue
            if re.fullmatch(r"[a-zA-Z_]\w*", p):
                # look for `name = 0xNN` numeric assign
                am = re.search(rf"(?:^|\n)\s*{re.escape(p)}\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*$", src, re.M)
                if am:
                    out.append(int(am.group(1), 0) & 0xFF)
                    continue
            ok = False
            break
        if ok and out:
            return bytes(out)

    # [CONST_OR_HEX_LIST].pack("H*")
    m = re.match(r"\[\s*(.+?)\s*\]\.pack\(\s*['\"]H\*['\"]\s*\)\s*$", expr)
    if m:
        inner = m.group(1).strip()
        if re.fullmatch(r"[A-Z][A-Z0-9_]*", inner):
            hx = resolve_hex_array_constant(inner, src)
            if hx is not None:
                return hx
        hexparts = re.findall(r"['\"]([0-9A-Fa-f]+)['\"]", inner)
        if hexparts:
            try:
                return bytes.fromhex("".join(hexparts))
            except ValueError:
                return None

    # Generic mixed-format pack, e.g. [id, seq, n, 0, "version\r\n"].pack("nnnna*")
    # — covers Auxiliary::UDPScanner build_probe bodies (header fields + a raw
    # tail string). Tried after the single-value and c*/C*/H* special cases
    # above so those keep taking priority where they already match.
    m = re.match(r"\[\s*(.+)\s*\]\.pack\(\s*['\"]([a-zA-Z0-9*]+)['\"]\s*\)\s*$", expr, re.S)
    if m:
        b = eval_pack_array(m.group(1), m.group(2), src, depth)
        if b is not None:
            return b

    # [expr.length].pack("N") << expr   /  [expr.length].pack("N") + expr
    m = re.match(
        r"\[\s*([a-zA-Z_]\w*)\.length\s*\]\.pack\(\s*['\"]N['\"]\s*\)\s*(?:<<|\+)\s*\1\s*$",
        expr,
    )
    if m:
        inner = resolve_var(m.group(1), src, depth + 1)
        if inner is not None:
            return struct.pack(">I", len(inner)) + inner

    # [expr.length + 4].pack("N") + expr   (postgres style)
    m = re.match(
        r"\[\s*([a-zA-Z_]\w*)\.length\s*\+\s*(\d+)\s*\]\.pack\(\s*['\"]N['\"]\s*\)\s*\+\s*\1\s*$",
        expr,
    )
    if m:
        var = m.group(1)
        extra = int(m.group(2))
        inner = resolve_var(var, src, depth + 1)
        if inner is not None:
            return struct.pack(">I", len(inner) + extra) + inner

    # Concatenation: a + b + c
    if "+" in expr:
        parts = split_top_level(expr, "+")
        if len(parts) > 1:
            out = bytearray()
            for p in parts:
                b = eval_bytes_expr(p.strip(), src, depth + 1)
                if b is None:
                    return None
                out.extend(b)
            return bytes(out)

    # Variable reference
    if re.fullmatch(r"[a-zA-Z_]\w*", expr):
        return resolve_var(expr, src, depth + 1)

    # datastore mutation like sploit[6] = ... — reject
    if "[" in expr and "]" in expr and "=" not in expr:
        # slice? skip
        return None

    return None


def resolve_hex_array_constant(name: str, src: str) -> bytes | None:
    """Resolve CONST = [ 'aabb', 'ccdd', ... ] used with .pack('H*')."""
    m = re.search(rf"(?:^|\n)\s*{re.escape(name)}\s*=\s*\[(.*?)\]", src, re.S)
    if not m:
        return None
    hexparts = re.findall(r"['\"]([0-9A-Fa-f]+)['\"]", m.group(1))
    if not hexparts:
        return None
    try:
        return bytes.fromhex("".join(hexparts))
    except ValueError:
        return None


# Pack-format codes we can fold deterministically. "a*"/"A*"/"Z*" consume one
# raw-bytes element (the probe's variable-length tail); the rest consume one
# integer element each. Repeat counts (e.g. "N2") and other pack codes are not
# supported — eval_pack_array returns None and the caller reports a skip.
_PACK_INT_CODES = {
    "n": (">H", 0xFFFF),
    "v": ("<H", 0xFFFF),
    "N": (">I", 0xFFFFFFFF),
    "V": ("<I", 0xFFFFFFFF),
    "C": (">B", 0xFF),
    "c": (">B", 0xFF),
}
_PACK_STR_CODES = {"a*", "A*", "Z*"}


def pack_mixed(parts: list, fmt: str) -> bytes | None:
    """Pack (int|bytes) parts per a Ruby Array#pack format string, e.g. "nnnna*"."""
    tokens = re.findall(r"a\*|A\*|Z\*|[nNvVCc]", fmt)
    if not tokens or len(tokens) != len(parts) or "".join(tokens) != fmt:
        return None
    out = bytearray()
    for tok, val in zip(tokens, parts):
        if tok in _PACK_STR_CODES:
            if not isinstance(val, (bytes, bytearray)):
                return None
            out += val
            if tok == "Z*":
                out += b"\x00"
            continue
        if isinstance(val, (bytes, bytearray)) or not isinstance(val, int):
            return None
        fmt_code, mask = _PACK_INT_CODES[tok]
        out += struct.pack(fmt_code, val & mask)
    return bytes(out)


def eval_pack_array(inner: str, fmt: str, src: str, depth: int) -> bytes | None:
    """Resolve `[e1, e2, ...].pack(fmt)` where each element folds to an int or
    bytes. `rand(...)` folds to 0 — any value is valid in a stateless probe's
    request-id/sequence field, we never validate it against the response."""
    parts_src = split_top_level(inner, ",")
    vals: list = []
    for p in parts_src:
        p = re.sub(r"#.*", "", p).strip()
        p = re.sub(r"\brand\s*\([^)]*\)", "0", p).strip()
        if not p:
            return None
        if re.fullmatch(r"0x[0-9A-Fa-f]+|\d+", p):
            vals.append(int(p, 0))
            continue
        b = eval_bytes_expr(p, src, depth + 1)
        if b is None:
            return None
        vals.append(b)
    return pack_mixed(vals, fmt)


def extract_build_probe(src: str) -> bytes | None:
    """Resolve Auxiliary::UDPScanner's `def build_probe ... end` to bytes.
    Handles the common `@ivar ||= [...].pack(fmt)` memoized-probe shape; the
    array literal may span multiple source lines (comments stripped per-line
    before flattening, so a trailing '#...' never swallows later elements)."""
    m = re.search(r"def\s+build_probe\b[^\n]*\n(.*?)\n\s*end\b", src, re.S)
    if not m:
        return None
    body = re.sub(r"#.*", "", m.group(1))
    expr = re.sub(r"\s+", " ", body).strip()
    expr = re.sub(r"^@\w+\s*\|?\|=\s*", "", expr)  # @ivar ||= ... / @ivar = ...
    expr = expr.strip()
    if expr.endswith(".freeze"):
        expr = expr[: -len(".freeze")].strip()
    if not expr:
        return None
    return eval_bytes_expr(expr, src, 0)


def split_top_level(expr: str, sep: str) -> list[str]:
    parts: list[str] = []
    depth = 0
    in_str = None
    esc = False
    cur = []
    i = 0
    while i < len(expr):
        ch = expr[i]
        if in_str:
            cur.append(ch)
            if esc:
                esc = False
            elif ch == "\\":
                esc = True
            elif ch == in_str:
                in_str = None
            i += 1
            continue
        if ch in "'\"":
            in_str = ch
            cur.append(ch)
            i += 1
            continue
        if ch in "([{":
            depth += 1
            cur.append(ch)
            i += 1
            continue
        if ch in ")]}":
            depth -= 1
            cur.append(ch)
            i += 1
            continue
        if depth == 0 and expr.startswith(sep, i):
            parts.append("".join(cur))
            cur = []
            i += len(sep)
            continue
        cur.append(ch)
        i += 1
    parts.append("".join(cur))
    return parts


def gather_multiline_assign(src: str, assign_end: int, first_line_rhs: str) -> str:
    """Gather a Ruby assignment RHS that continues with + / << across lines."""
    full = first_line_rhs.rstrip()
    if not (full.endswith("+") or full.endswith("<<") or full.endswith("(")):
        # Still gather if next non-empty lines are string literals being concatenated
        lines = src[assign_end:].splitlines()
        if lines and re.match(r"^\s*['\"]", lines[0] if False else ""):
            pass
        return full
    more: list[str] = []
    for line in src[assign_end:].splitlines()[0:40]:
        s = line.strip()
        if not s or s.startswith("#"):
            if more and not more[-1].endswith("+"):
                break
            continue
        # stop on unrelated statements
        if re.match(r"^(sock\.|connect|disconnect|if\b|unless\b|while\b|return\b|end\b|print_|select\b)", s):
            break
        more.append(s)
        if not (s.endswith("+") or s.endswith("<<")):
            # one more line might be final piece without trailing +
            break
    return (full + " " + " ".join(more)).replace("<<", "+")


def resolve_constant(name: str, src: str, depth: int) -> bytes | None:
    # SMI_PROBE = "....".freeze
    # VERSION = "..." \  (line continuation)
    m = re.search(
        rf"(?:^|\n)\s*{re.escape(name)}\s*=\s*",
        src,
    )
    if not m:
        return None
    i = m.end()
    # Gather until we hit a line that isn't a string continuation
    chunk = []
    # Read from i: may be "..." \ or "..." + or "..."
    rest = src[i:]
    # Collapse Ruby line-continuation backslash-newline inside/between strings
    rest = re.sub(r"\\\s*\n\s*", "", rest)
    # Take first statement (until newline that's not inside a string — simplified: until .freeze or bare newline after closing quote)
    m2 = re.match(
        r"((?:'(?:\\'|[^'])*'|\"(?:\\\"|\\x[0-9A-Fa-f]{2}|\\[nrt0]|[^\"])*\")(?:\s*\+\s*(?:'(?:\\'|[^'])*'|\"(?:\\\"|\\x[0-9A-Fa-f]{2}|\\[nrt0]|[^\"])*\"))*)(?:\.freeze)?",
        rest,
    )
    if not m2:
        # single line fallback
        line = rest.split("\n", 1)[0].replace(".freeze", "").strip()
        return eval_bytes_expr(line, src, depth + 1)
    return eval_bytes_expr(m2.group(1), src, depth + 1)


def resolve_var(name: str, src: str, depth: int) -> bytes | None:
    # Find assignments name = <expr>, then apply subsequent name << <expr>
    assigns = list(
        re.finditer(rf"(?:^|\n)\s*{re.escape(name)}\s*=\s*([^\n]+)", src)
    )
    if not assigns:
        return None
    for a in reversed(assigns):
        rhs = a.group(1).strip()
        full = gather_multiline_assign(src, a.end(), rhs)
        full = re.sub(r"\s+#.*$", "", full).strip().rstrip("+").strip()
        b = eval_bytes_expr(full, src, depth + 1)
        if b is None:
            continue
        # Apply name << pieces after this assignment until next name = or end of method-ish block
        pos = a.end()
        for m in re.finditer(
            rf"(?:^|\n)\s*{re.escape(name)}\s*(<<|=)\s*([^\n]+)",
            src[pos : pos + 4000],
        ):
            op = m.group(1)
            if op == "=":
                break
            piece_rhs = re.sub(r"\s+#.*$", "", m.group(2)).strip()
            piece = eval_bytes_expr(piece_rhs, src, depth + 1)
            if piece is None:
                break
            b = b + piece
        return b
    return None


def resolve_method_body_bytes(body: str, src: str, depth: int) -> bytes | None:
    # Collect top-level string literal concatenations (ignore comments)
    # Pattern: method returns implicit last string expr
    cleaned = re.sub(r"#.*", "", body)
    # Try entire body as one concat of string literals and + lines
    literals = re.findall(
        r"('(?:\\'|[^'])*'|\"(?:\\\"|\\x[0-9A-Fa-f]{2}|\\[nrt0]|[^\"])*\")",
        cleaned,
    )
    if not literals:
        return None
    # If body is ONLY string literals joined by + / newlines, concat them
    stripped = re.sub(
        r"('(?:\\'|[^'])*'|\"(?:\\\"|\\x[0-9A-Fa-f]{2}|\\[nrt0]|[^\"])*\")|\s|\+",
        "",
        cleaned,
    )
    # Allow only punctuation leftover empty
    if stripped.strip() not in ("", "end"):
        # might have other code — if only one literal and little else, still try first literal chain at start
        # For connection_request style methods that are pure concat, stripped is empty.
        # If there's pack/etc, fail.
        if re.search(r"pack|datastore|sock\.|connect|if\b|while\b", cleaned):
            return None
    out = bytearray()
    for lit in literals:
        b = decode_ruby_string(lit)
        if b is None:
            return None
        out.extend(b)
    return bytes(out) if out else None


def find_put_args(src: str) -> list[str]:
    """Extract first-arg expressions from sock.put/write/puts calls (paren-balanced)."""
    args: list[str] = []
    for m in re.finditer(r"(?:sock|s|udp_sock)\.(?:put|write|puts)\s*\(", src):
        start = m.end()
        depth = 1
        i = start
        in_str = None
        esc = False
        while i < len(src) and depth:
            ch = src[i]
            if in_str:
                if esc:
                    esc = False
                elif ch == "\\":
                    esc = True
                elif ch == in_str:
                    in_str = None
                i += 1
                continue
            if ch in "'\"":
                in_str = ch
                i += 1
                continue
            if ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
                if depth == 0:
                    break
            i += 1
        if depth != 0:
            continue
        arg = src[start:i].strip()
        if "," in arg:
            parts = split_top_level(arg, ",")
            arg = parts[0].strip() if parts else arg
        # Skip obviously non-probe (rescue blocks leaked etc.)
        if "\n" in arg and ("rescue" in arg or "disconnect" in arg):
            continue
        args.append(arg)
    return args


def find_bare_call_args(src: str, name: str) -> list[str]:
    """Like find_put_args but for a bare method call, e.g. scanner_send(data, ip, rport)."""
    args: list[str] = []
    for m in re.finditer(rf"\b{re.escape(name)}\s*\(", src):
        start = m.end()
        depth = 1
        i = start
        in_str = None
        esc = False
        while i < len(src) and depth:
            ch = src[i]
            if in_str:
                if esc:
                    esc = False
                elif ch == "\\":
                    esc = True
                elif ch == in_str:
                    in_str = None
                i += 1
                continue
            if ch in "'\"":
                in_str = ch
                i += 1
                continue
            if ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
                if depth == 0:
                    break
            i += 1
        if depth != 0:
            continue
        arg = src[start:i].strip()
        if "," in arg:
            parts = split_top_level(arg, ",")
            arg = parts[0].strip() if parts else arg
        args.append(arg)
    return args


def extract_matchers(src: str) -> list[Matcher]:
    matchers: list[Matcher] = []
    # resp =~ /process_postgres_switches/
    for m in re.finditer(r"=~\s*/((?:\\/|[^/])+)/", src):
        pat = m.group(1)
        # skip very generic
        if pat in (".", ".*", ".+"):
            continue
        matchers.append(Matcher("regex", [pat]))
    # data == "\xD0\x15\x00\x00"
    for m in re.finditer(
        r"(?:==|!=)\s*(\"(?:\\x[0-9A-Fa-f]{2}|\\[nrt0]|[^\"])*\"|'(?:\\'|[^'])*')",
        src,
    ):
        b = decode_ruby_string(m.group(1))
        if b and 1 <= len(b) <= 64:
            matchers.append(Matcher("binary", [b.hex()]))
    # data[0, 4] == "\x21\x00\x00\x00"
    for m in re.finditer(
        r"\[\s*0\s*,\s*\d+\s*\]\s*==\s*(\"(?:\\x[0-9A-Fa-f]{2}|\\[nrt0]|[^\"])*\"|'(?:\\'|[^'])*')",
        src,
    ):
        b = decode_ruby_string(m.group(1))
        if b:
            matchers.append(Matcher("binary", [b.hex()]))
    # start_with?("MMcS") / start_with?('ScMM') — collapse to one OR regex
    starts = re.findall(r"start_with\?\(\s*['\"]([^'\"]{2,32})['\"]\s*\)", src)
    if starts:
        # Escape for regex alternation
        alts = "|".join(re.escape(s) for s in dict.fromkeys(starts))
        matchers.append(Matcher("regex", [alts]))
    # =~ /robotd~robotd~CLIENT/
    # word match for ASCII printable strings in include?/include?
    for m in re.finditer(
        r"(?:include\?|match|=~)\s*\(?\s*['\"]([A-Za-z0-9 _.<>-]{4,})['\"]",
        src,
    ):
        matchers.append(Matcher("word", [m.group(1)]))
    # Please press <Enter>
    for m in re.finditer(r"['\"]([A-Za-z][^'\"]{6,80})['\"]", src):
        s = m.group(1)
        if "press" in s.lower() or "Banner" in s or "ready" in s.lower():
            if "\\x" not in s and "#{" not in s:
                matchers.append(Matcher("word", [s[:60]]))

    # Dedupe
    seen = set()
    out = []
    for mt in matchers:
        key = (mt.mtype, tuple(mt.values))
        if key in seen:
            continue
        seen.add(key)
        out.append(mt)
    return out[:3]  # keep yaml small


def slug_from_rel(rel: str) -> str:
    stem = rel.replace("\\", "/").removesuffix(".rb")
    slug = re.sub(r"[^a-zA-Z0-9]+", "-", stem).strip("-").lower()
    return slug


def yaml_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fold_desc(s: str, width: int = 76) -> str:
    s = re.sub(r"\s+", " ", s).strip()
    if not s:
        return "Ported automatically from Metasploit auxiliary/scanner."
    return s


def _emit_input_lines(item: bytes | str) -> list[str]:
    """Format one tcp input entry (text or hex)."""
    if isinstance(item, str):
        esc = (
            item.replace("\\", "\\\\")
            .replace('"', '\\"')
            .replace("\r", "\\r")
            .replace("\n", "\\n")
            .replace("\t", "\\t")
            .replace("\x1b", "\\x1b")
        )
        return [f'      - data: "{esc}"']
    if all(32 <= b < 127 or b in (9, 10, 13, 0x1B) for b in item) and len(item) < 800:
        text = "".join(chr(b) if b != 0x1B else "\\x1b" for b in item)
        # Prefer hex when ESC present — YAML escape of \x1b is awkward for parsers
        if 0x1B in item:
            return [f'      - data: "{item.hex()}"', "        type: hex"]
        esc = (
            text.replace("\\", "\\\\")
            .replace('"', '\\"')
            .replace("\r", "\\r")
            .replace("\n", "\\n")
            .replace("\t", "\\t")
        )
        return [f'      - data: "{esc}"']
    return [f'      - data: "{item.hex()}"', "        type: hex"]


def emit_yaml(
    rel: str,
    name: str,
    authors: str,
    desc: str,
    tags: list[str],
    rport: int,
    probe: Probe,
    matchers: list[Matcher],
    cves: list[str],
    text_probe: str | None = None,
    extra_inputs: list[bytes | str] | None = None,
    udp: bool = False,
) -> str:
    slug = slug_from_rel(rel)
    tid = f"msf-{slug}"
    ref = (
        "https://github.com/rapid7/metasploit-framework/blob/master/"
        f"modules/auxiliary/scanner/{rel}"
    )
    sev = "info"
    if any(t in tags for t in ("backdoor", "malware", "c2")):
        sev = "critical"
    elif cves:
        sev = "high"

    lines = [
        AUTO_MARKER.rstrip("\n"),
        f"id: {tid}",
        "",
        "info:",
        f"  name: {name}",
        (
            f"  author: {authors} (ported from metasploit-framework "
            f"auxiliary/scanner/{rel.removesuffix('.rb')})"
        ),
        f"  severity: {sev}",
        "  description: |",
        f"    {fold_desc(desc)}",
        "  reference:",
        f"    - {ref}",
    ]
    if cves:
        lines += ["  classification:", f"    cve-id: {cves[0]}"]
    lines.append(f"  tags: {','.join(['msf'] + tags)}")
    lines.append("")
    lines.append("tcp:")

    input_items: list[bytes | str] = []
    if extra_inputs:
        input_items.extend(extra_inputs)
    elif text_probe is not None:
        input_items.append(text_probe)
    elif probe.kind == "probe" and probe.data:
        input_items.append(probe.data)

    if input_items:
        lines.append("  - inputs:")
        for item in input_items:
            lines.extend(_emit_input_lines(item))
        lines.append("    host:")
    else:
        lines.append("  - host:")

    lines.append('      - "{{Hostname}}"')
    # SSH checks follow the discovered/selected endpoint, including custom ports.
    if rel != "ssh/ssh_version.rb":
        lines.append(f"    port: {rport}")
    lines.append("    read-size: 4096")
    if udp:
        lines.append("    udp: true")

    if not matchers:
        matchers = [Matcher("regex", ["."])]

    lines.append("    matchers:")
    for mt in matchers:
        lines.append(f"      - type: {mt.mtype}")
        lines.append("        part: data")
        key = {"regex": "regex", "word": "words", "binary": "binary"}[mt.mtype]
        lines.append(f"        {key}:")
        for v in mt.values:
            lines.append(f'          - "{yaml_escape(v)}"')

    if probe.kind == "banner":
        lines += [
            "    extractors:",
            "      - type: regex",
            "        part: data",
            "        regex:",
            '          - "^(.+)"',
        ]

    lines.append("")
    return "\n".join(lines)


